    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
try {
    Estudiante estudiante = obtenerEstudianteFormulario(0);

    if (estudianteDAO.insertar(estudiante)) {
        JOptionPane.showMessageDialog(this, "Estudiante registrado");
        cargarEstudiantes();
        limpiarCampos();
    } else {
        JOptionPane.showMessageDialog(this, "No se pudo registrar");
    }
} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
int fila = tblEstudiantes.getSelectedRow();

if (fila == -1) {
    JOptionPane.showMessageDialog(this, "Seleccione un estudiante");
    return;
}

try {
    int id = Integer.parseInt(
        tblEstudiantes.getValueAt(fila, 0).toString()
    );

    Estudiante estudiante = obtenerEstudianteFormulario(id);

    if (estudianteDAO.actualizar(estudiante)) {
        JOptionPane.showMessageDialog(this, "Estudiante actualizado");
        cargarEstudiantes();
        limpiarCampos();
    } else {
        JOptionPane.showMessageDialog(this, "No se pudo actualizar");
    }
} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
int fila = tblEstudiantes.getSelectedRow();

if (fila == -1) {
    JOptionPane.showMessageDialog(this, "Seleccione un estudiante");
    return;
}

int id = Integer.parseInt(
    tblEstudiantes.getValueAt(fila, 0).toString()
);

int respuesta = JOptionPane.showConfirmDialog(
    this,
    "¿Eliminar este estudiante?",
    "Confirmar",
    JOptionPane.YES_NO_OPTION
);

if (respuesta == JOptionPane.YES_OPTION) {
    if (estudianteDAO.eliminar(id)) {
        JOptionPane.showMessageDialog(this, "Estudiante eliminado");
        cargarEstudiantes();
        limpiarCampos();
    } else {
        JOptionPane.showMessageDialog(
            this, "No se pudo eliminar. Puede tener préstamos asociados."
        );
    }
}
    }//GEN-LAST:event_btnEliminarActionPerformed

