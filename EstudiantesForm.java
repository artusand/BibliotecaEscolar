private final EstudianteDAO estudianteDAO = new EstudianteDAO();

private void cargarEstudiantes() {
    DefaultTableModel modelo = new DefaultTableModel(
        new Object[]{"ID", "Nombre", "RUT", "Curso", "Correo"}, 0
    ) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };

    for (Estudiante estudiante : estudianteDAO.listar()) {
        modelo.addRow(new Object[]{
            estudiante.getId(),
            estudiante.getNombre(),
            estudiante.getRut(),
            estudiante.getCurso(),
            estudiante.getCorreo()
        });
    }

    tblEstudiantes.setModel(modelo);
}

private void limpiarCampos() {
    txtNombre.setText("");
    txtRut.setText("");
    txtCurso.setText("");
    txtCorreo.setText("");
    tblEstudiantes.clearSelection();
}

private Estudiante obtenerEstudianteFormulario(int id) {
    String nombre = txtNombre.getText().trim();
    String rut = txtRut.getText().trim();
    String curso = txtCurso.getText().trim();
    String correo = txtCorreo.getText().trim();

    if (nombre.isEmpty() || rut.isEmpty()
            || curso.isEmpty() || correo.isEmpty()) {
        throw new IllegalArgumentException("Complete todos los campos");
    }

    return new Estudiante(id, nombre, rut, correo, curso);
}


